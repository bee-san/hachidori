// docs/evidence/issue-330/themes/rpg-dialogue/pixel-css.mjs — generates the
// box-shadow pixel art pasted into themes/rpg-dialogue/theme.css (issue #334).
// Every sprite below is original: the hummingbird portrait, the pointing-hand
// and ▼ cursors and a 3×5 pixel font. No image files, no fonts, no url():
// one <i> with a box-shadow per lit pixel; `--s` is the pixel size.
//
//   node pixel-css.mjs > pixel-art.css

const S = 2; // px per sprite pixel

function shadows(rows, colors, unit = S) {
  const list = [];
  rows.forEach((row, y) => {
    [...row].forEach((cell, x) => {
      const color = colors[cell];
      if (!color) return;
      list.push(`${x * unit}px ${y * unit}px 0 0 ${color}`);
    });
  });
  return list.join(", ");
}

